import Foundation
import CryptoKit
import zlib

func gzip(_ data: Data) throws -> Data {
    var stream = z_stream()
    guard deflateInit2_(&stream, 9, Z_DEFLATED, 15 + 16, 8, Z_DEFAULT_STRATEGY,
                       ZLIB_VERSION, Int32(MemoryLayout<z_stream>.size)) == Z_OK else {
        throw NSError(domain: "gzip", code: 1)
    }
    defer { deflateEnd(&stream) }
    var output = Data(count: Int(compressBound(uLong(data.count))) + 64)
    let capacity = output.count
    let status = data.withUnsafeBytes { input in
        output.withUnsafeMutableBytes { buffer in
            stream.next_in = UnsafeMutablePointer(mutating: input.bindMemory(to: UInt8.self).baseAddress!)
            stream.avail_in = uInt(input.count)
            stream.next_out = buffer.bindMemory(to: UInt8.self).baseAddress!
            stream.avail_out = uInt(capacity)
            return deflate(&stream, Z_FINISH)
        }
    }
    guard status == Z_STREAM_END else { throw NSError(domain: "gzip", code: Int(status)) }
    output.count = Int(stream.total_out)
    return output
}

